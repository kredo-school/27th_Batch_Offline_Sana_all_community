                        <strong>通報・コンテンツ削除ポリシー</strong> <br>
                        <strong>Report & Content Removal Policy</strong> <br>

制定日 / Effective Date：20XX年XX月XX日

1. 目的

1. Purpose

本ポリシーは、投稿、コメント、プロフィール、画像、求人、イベント、広告その他のコンテンツについて通報を受けた場合の対応方針を定めます。

This Policy explains how we handle reports concerning posts, comments,
profiles, images, job listings, events, advertisements, and other
content.

2. 通報できる内容

2. What Can Be Reported

利用規約・ガイドライン違反 / Terms or Guidelines violations

詐欺または詐欺の疑い / Fraud or suspected fraud

嫌がらせ、脅迫、差別 / Harassment, threats, or discrimination

個人情報の不正な掲載 / Unauthorized disclosure of personal
information

著作権・商標権等の侵害 / Intellectual property infringement

虚偽・誤解を招く求人、イベント、広告 / False or misleading jobs,
events, or advertisements

違法な商品・サービス / Illegal goods or services

スパム、なりすまし、フィッシング / Spam, impersonation, or phishing

その他、重大な安全上またはコミュニティ上の懸念 / Other serious
safety or community concerns

3. 通報方法

3. How to Report

サイト内のReport機能または運営者指定の連絡先から通報してください。可能な限り、対象コンテンツのURL、通報理由、具体的な問題、判断に役立つ情報を提供してください。

Use the Site's Report function or the contact channel designated by the
Operator. Where possible, include the content URL, reason for the
report, specific concern, and relevant supporting information.

虚偽の通報、嫌がらせを目的とした大量通報、他のユーザーを攻撃するための通報は禁止します。

False reports and mass reporting intended to harass or target another
user are prohibited.

4. 確認と判断

4. Review and Assessment

運営者は、規約違反の有無、適用法令、他人の権利、安全へのリスク、違反の重大性や反復性、コミュニティへの影響等を考慮して判断します。

The Operator may consider whether rules or laws may have been violated,
potential infringement of rights, safety risks, severity and repetition,
and impact on the community.

5. 緊急性の高い通報

5. Urgent Reports

生命や身体への差し迫った危険、深刻な脅迫、重大な犯罪、個人情報の重大な漏えい等は優先して確認する場合があります。本サイトは緊急サービスではありません。差し迫った危険がある場合は、フィリピンの適切な緊急機関または法執行機関へ連絡してください。

Reports involving imminent danger, serious threats, major criminal
activity, or significant exposure of personal information may receive
priority. The Site is not an emergency service. Contact appropriate
Philippine emergency services or law enforcement if there is immediate
danger.

6. 対応措置

6. Possible Actions

運営者は、必要に応じてコンテンツの削除・非公開、表示制限、警告、機能制限、一時停止、アカウント停止・削除等を行うことがあります。重大な違反や緊急時には事前警告なしに対応する場合があります。

Where appropriate, the Operator may remove or hide content, limit
visibility or features, issue warnings, temporarily suspend accounts, or
terminate accounts. Serious or urgent cases may be handled without prior
warning.

7. 削除しない場合

7. When Content May Not Be Removed

通報があったことだけを理由に、必ず削除するわけではありません。単に意見が異なる、気に入らない、批判的であるという理由だけでは、必ずしも削除対象になりません。ただし、脅迫、嫌がらせ、差別、虚偽情報その他の違反がある場合は対応することがあります。

A report does not automatically result in removal. Content is not
necessarily removed merely because someone disagrees with it, dislikes
it, or finds it critical. Action may be taken if the content also
violates rules.

8. ユーザー間の取引トラブル

8. Disputes Between Users

運営者は、ユーザー間取引の当事者ではなく、商品の品質、未着、支払い、返金、キャンセル、価格、契約条件等の通常の紛争には原則として介入しません。ただし、詐欺、違法行為、脅迫、嫌がらせ、個人情報の悪用その他の規約違反が疑われる場合、関連投稿やアカウントに対応することがあります。

The Operator is not a party to transactions between users and generally
does not mediate ordinary disputes about quality, delivery, payment,
refunds, cancellations, pricing, or contract terms. However, action may
be taken against content or accounts where fraud, illegal activity,
threats, harassment, misuse of personal information, or other policy
violations are suspected.

9. 求人・広告・イベントの通報

9. Reports About Jobs, Ads, and Events

架空の求人、不当な金銭要求、虚偽の給与条件、詐欺的なイベント、誤解を招く広告、違法な商品・サービス等を通報できます。運営者はすべての掲載情報の真偽を保証するものではありません。

Users may report fake jobs, improper payment demands, misleading salary
terms, fraudulent events, misleading advertisements, and illegal goods
or services. The Operator does not guarantee the accuracy or legitimacy
of every listing.

10. 知的財産に関する通報

10. Intellectual Property Reports

対象URL、権利者または代理人であることの説明、侵害が疑われる権利とコンテンツの説明、確認に必要な情報を提供してください。虚偽の申告は禁止します。

Please provide the URL, an explanation of your authority or relationship
to the rights holder, a description of the right and content at issue,
and relevant supporting information. False claims are prohibited.

11. 異議申し立て

11. Appeals

措置を受けたユーザーは、対象コンテンツまたはアカウント、措置内容、異議の理由を記載して、運営者指定の方法で見直しを求めることができます。運営者は提出情報を確認し、必要に応じて再検討します。

Users affected by enforcement may request review through the designated
channel, identifying the content or account, action taken, and reasons
for appeal. The Operator will review the information and reconsider
where appropriate.

12. 通報者情報・法的要請

12. Reporter Information and Legal Requests

通報者の個人情報は、適用法令およびPrivacy
Policyに従って取り扱います。原則として通報者の身元を対象ユーザーに開示しませんが、法律上の義務や適法な手続き等により開示が必要な場合があります。

Reporter information is handled in accordance with applicable law and
the Privacy Policy. We generally do not disclose a reporter's identity
to the reported user, except where required by law or valid legal
process.

13. 変更・お問い合わせ

13. Changes and Contact

本ポリシーは必要に応じて更新されます。

This Policy may be updated when necessary.

