                    <p>
                        <strong>通報・コンテンツ削除ポリシー</strong> <br>
                        <strong>Report & Content Removal Policy</strong> <br>

制定日 / Effective Date：20XX年XX月XX日<br>
<br>
1. 目的<br>
<br>
1. Purpose<br>
<br>
本ポリシーは、投稿、コメント、プロフィール、画像、求人、イベント、広告その他のコンテンツについて通報を受けた場合の対応方針を定めます。<br>
<br>
This Policy explains how we handle reports concerning posts, comments,<br>
profiles, images, job listings, events, advertisements, and other<br>
content.<br>
<br>
2. 通報できる内容<br>
<br>
2. What Can Be Reported<br>
<br>
利用規約・ガイドライン違反 / Terms or Guidelines violations<br>
<br>
詐欺または詐欺の疑い / Fraud or suspected fraud<br>
<br>
嫌がらせ、脅迫、差別 / Harassment, threats, or discrimination<br>
<br>
個人情報の不正な掲載 / Unauthorized disclosure of personal<br>
information<br>
<br>
著作権・商標権等の侵害 / Intellectual property infringement<br>
<br>
虚偽・誤解を招く求人、イベント、広告 / False or misleading jobs,<br>
events, or advertisements<br>
<br>
違法な商品・サービス / Illegal goods or services<br>
<br>
スパム、なりすまし、フィッシング / Spam, impersonation, or phishing<br>
<br>
その他、重大な安全上またはコミュニティ上の懸念 / Other serious<br>
safety or community concerns<br>
<br>
3. 通報方法<br>
<br>
3. How to Report<br>
<br>
サイト内のReport機能または運営者指定の連絡先から通報してください。可能な限り、対象コンテンツのURL、通報理由、具体的な問題、判断に役立つ情報を提供してください。<br>
<br>
Use the Site's Report function or the contact channel designated by the<br>
Operator. Where possible, include the content URL, reason for the<br>
report, specific concern, and relevant supporting information.<br>
<br>
虚偽の通報、嫌がらせを目的とした大量通報、他のユーザーを攻撃するための通報は禁止します。<br>
<br>
False reports and mass reporting intended to harass or target another<br>
user are prohibited.<br>
<br>
4. 確認と判断<br>
<br>
4. Review and Assessment<br>
<br>
運営者は、規約違反の有無、適用法令、他人の権利、安全へのリスク、違反の重大性や反復性、コミュニティへの影響等を考慮して判断します。<br>
<br>
The Operator may consider whether rules or laws may have been violated,<br>
potential infringement of rights, safety risks, severity and repetition,<br>
and impact on the community.<br>
<br>
5. 緊急性の高い通報<br>
<br>
5. Urgent Reports<br>
<br>
生命や身体への差し迫った危険、深刻な脅迫、重大な犯罪、個人情報の重大な漏えい等は優先して確認する場合があります。本サイトは緊急サービスではありません。差し迫った危険がある場合は、フィリピンの適切な緊急機関または法執行機関へ連絡してください。<br>
<br>
Reports involving imminent danger, serious threats, major criminal<br>
activity, or significant exposure of personal information may receive<br>
priority. The Site is not an emergency service. Contact appropriate<br>
Philippine emergency services or law enforcement if there is immediate<br>
danger.<br>
<br>
6. 対応措置<br>
<br>
6. Possible Actions<br>
<br>
運営者は、必要に応じてコンテンツの削除・非公開、表示制限、警告、機能制限、一時停止、アカウント停止・削除等を行うことがあります。重大な違反や緊急時には事前警告なしに対応する場合があります。<br>
<br>
Where appropriate, the Operator may remove or hide content, limit<br>
visibility or features, issue warnings, temporarily suspend accounts, or<br>
terminate accounts. Serious or urgent cases may be handled without prior<br>
warning.<br>
<br>
7. 削除しない場合<br>
<br>
7. When Content May Not Be Removed<br>
<br>
通報があったことだけを理由に、必ず削除するわけではありません。単に意見が異なる、気に入らない、批判的であるという理由だけでは、必ずしも削除対象になりません。ただし、脅迫、嫌がらせ、差別、虚偽情報その他の違反がある場合は対応することがあります。<br>
<br>
A report does not automatically result in removal. Content is not<br>
necessarily removed merely because someone disagrees with it, dislikes<br>
it, or finds it critical. Action may be taken if the content also<br>
violates rules.<br>
<br>
8. ユーザー間の取引トラブル<br>
<br>
8. Disputes Between Users<br>
<br>
運営者は、ユーザー間取引の当事者ではなく、商品の品質、未着、支払い、返金、キャンセル、価格、契約条件等の通常の紛争には原則として介入しません。ただし、詐欺、違法行為、脅迫、嫌がらせ、個人情報の悪用その他の規約違反が疑われる場合、関連投稿やアカウントに対応することがあります。<br>
<br>
The Operator is not a party to transactions between users and generally<br>
does not mediate ordinary disputes about quality, delivery, payment,<br>
refunds, cancellations, pricing, or contract terms. However, action may<br>
be taken against content or accounts where fraud, illegal activity,<br>
threats, harassment, misuse of personal information, or other policy<br>
violations are suspected.<br>
<br>
9. 求人・広告・イベントの通報<br>
<br>
9. Reports About Jobs, Ads, and Events<br>
<br>
架空の求人、不当な金銭要求、虚偽の給与条件、詐欺的なイベント、誤解を招く広告、違法な商品・サービス等を通報できます。運営者はすべての掲載情報の真偽を保証するものではありません。<br>
<br>
Users may report fake jobs, improper payment demands, misleading salary<br>
terms, fraudulent events, misleading advertisements, and illegal goods<br>
or services. The Operator does not guarantee the accuracy or legitimacy<br>
of every listing.<br>
<br>
10. 知的財産に関する通報<br>
<br>
10. Intellectual Property Reports<br>
<br>
対象URL、権利者または代理人であることの説明、侵害が疑われる権利とコンテンツの説明、確認に必要な情報を提供してください。虚偽の申告は禁止します。<br>
<br>
Please provide the URL, an explanation of your authority or relationship<br>
to the rights holder, a description of the right and content at issue,<br>
and relevant supporting information. False claims are prohibited.<br>
<br>
11. 異議申し立て<br>
<br>
11. Appeals<br>
<br>
措置を受けたユーザーは、対象コンテンツまたはアカウント、措置内容、異議の理由を記載して、運営者指定の方法で見直しを求めることができます。運営者は提出情報を確認し、必要に応じて再検討します。<br>
<br>
Users affected by enforcement may request review through the designated<br>
channel, identifying the content or account, action taken, and reasons<br>
for appeal. The Operator will review the information and reconsider<br>
where appropriate.<br>
<br>
12. 通報者情報・法的要請<br>
<br>
12. Reporter Information and Legal Requests<br>
<br>
通報者の個人情報は、適用法令およびPrivacy<br>
Policyに従って取り扱います。原則として通報者の身元を対象ユーザーに開示しませんが、法律上の義務や適法な手続き等により開示が必要な場合があります。<br>
<br>
Reporter information is handled in accordance with applicable law and<br>
the Privacy Policy. We generally do not disclose a reporter's identity<br>
to the reported user, except where required by law or valid legal<br>
process.<br>
<br>
13. 変更・お問い合わせ<br>
<br>
13. Changes and Contact<br>
<br>
本ポリシーは必要に応じて更新されます。<br>
<br>
This Policy may be updated when necessary.<br>
