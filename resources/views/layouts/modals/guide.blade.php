                    <strong>コミュニティガイドライン</strong><br>
                    <strong>Community Guidelines</strong> <br>

制定日 / Effective Date：20XX年XX月XX日 <br>

1. 私たちのコミュニティについて <br>
About Our Community <br>
<br>
このコミュニティは、さまざまな人が情報を共有し、交流し、イベントや仕事、店舗・サービスなどの情報を見つけるための場所です。 <br>

誰もが安心して参加できるコミュニティを作るため、以下のガイドラインを定めています。<br>

This community is a place where people can share information, connect with others, discover events and jobs, and promote businesses and services.<br>

These guidelines are designed to help keep the community welcoming, useful, and safe for everyone.<br>

2. 歓迎される投稿 <br>
What We Welcome <br>

以下のような投稿を歓迎します。<br>

We welcome posts such as: <br>

🗣 情報共有 / Information Sharing <br>

地域の情報、役立つ情報、経験、レビュー、質問など。<br>

Local information, useful tips, experiences, reviews, questions, and recommendations.<br>

🎉 イベント / Events <br>

イベント、交流会、セミナー、パーティー、スポーツ、コミュニティ活動など。<br>

Events, meetups, seminars, parties, sports activities, and community gatherings.<br>

💼 求人・仕事探し / Jobs <br>

求人情報、仕事を探している人の投稿、フリーランス・ビジネス関連の情報など。<br>

Job opportunities, employment searches, freelance opportunities, and business-related opportunities.<br>

🏪 店舗・サービスの宣伝 / Business Promotion <br>

自分の店舗、会社、サービス、商品などの宣伝を歓迎します。<br>

You are welcome to promote your own store, company, service, product, or business.<br>

ただし、虚偽の情報、過度なスパム、違法な商品・サービスの宣伝は禁止されています。<br>

However, false or misleading advertising, excessive spam, and promotion of illegal goods or services are prohibited.<br>

🤝 個人間取引 / Peer-to-Peer Transactions <br>

商品やサービスの売買、譲渡、交換などに関する投稿ができます。<br>

Users may post about buying, selling, exchanging, or giving away goods and services.<br>

個人間取引は、必ず双方の責任で行ってください。<br>

All peer-to-peer transactions are conducted at the users' own risk.<br>

3. 他の人を尊重しましょう <br>
Respect Other People <br>

意見や考え方が違っていても、お互いを尊重してください。<br>

Please respect other people, even when you disagree with their opinions or perspectives.<br>

以下のような行為は禁止します。<br>

The following are not allowed: <br>

誹謗中傷 / Harassment or personal attacks <br>
脅迫 / Threats <br>
差別的な発言 / Discriminatory content <br>
侮辱的な発言 / Abusive or insulting content <br>
ストーカー行為 / Stalking <br>
他人を意図的に傷つける行為 / Deliberately targeting or harming another user <br>
個人情報を利用した嫌がらせ / Harassment involving someone's personal information <br>

「意見への反論」は歓迎しますが、「人への攻撃」はやめましょう。<br>

Disagree with ideas, not with people.<br>

4. 個人情報を守りましょう <br>
Protect Personal Information<br>

本人の許可なく、他人の個人情報を投稿しないでください。<br>

Do not post another person's personal information without their permission or other lawful basis.<br>

以下の情報には特に注意してください。<br>

Please be especially careful with:<br>

電話番号 / Phone numbers<br>
メールアドレス / Email addresses<br>
自宅住所 / Home addresses<br>
パスポート・ID情報 / Passport or ID information<br>
銀行口座情報 / Bank account information<br>
クレジットカード情報 / Credit card information<br>
個人的なSNSアカウント / Private social media accounts<br>
個人を特定できるその他の情報 / Other information that can identify a person<br>

他人の写真や動画を投稿する場合も、本人のプライバシーや権利に配慮してください。<br>

When posting photographs or videos of other people, respect their privacy and applicable rights.<br>

5. 宣伝・広告について<br>
Advertising and Promotion<br>

自分の店舗、会社、サービス、商品などを宣伝することができます。<br>

You may promote your own business, store, service, product, or other legitimate activity.<br>

ただし、以下は禁止します。<br>

However, the following are not allowed:<br>

同じ広告を短時間に大量投稿する / Repeatedly posting the same advertisement<br>
他の投稿に無関係な広告を大量に返信する / Spamming unrelated advertisements in other posts<br>
虚偽の価格やサービス内容を掲載する / False pricing or service information<br>
誤解を招く広告 / Misleading advertising<br>
違法な商品・サービスの宣伝 / Promotion of illegal goods or services<br>
他社や他人を意図的に中傷する広告 / Advertising intended to maliciously attack competitors or individuals<br>

運営者は、コミュニティの品質を維持するため、広告の掲載方法や頻度について制限を設ける場合があります。<br>

We may limit the frequency or manner of advertising to maintain the quality of the community.<br>

6. 求人情報について<br>
Job Listings<br>

求人情報を掲載する場合は、できるだけ具体的で正確な情報を掲載してください。<br>

When posting a job opportunity, provide accurate and sufficiently detailed information.<br>

可能であれば、以下を明記してください。<br>

Where applicable, include:<br>

会社・店舗名 / Company or business name<br>
勤務地 / Location<br>
職種 / Position<br>
給与・報酬 / Salary or compensation<br>
勤務時間 / Working hours<br>
主な仕事内容 / Main responsibilities<br>
応募方法 / How to apply<br>

以下は禁止します。<br>

The following are prohibited:<br>

架空の求人 / Fake job listings<br>
詐欺目的の求人 / Fraudulent recruitment<br>
求人を利用した金銭詐欺 / Recruitment-related financial scams<br>
虚偽の給与・条件 / False salary or employment conditions<br>
応募者から不当に金銭を要求する行為 / Unreasonable demands for money from applicants<br>

求人に応募する場合も、相手の会社・人物・条件などを自分で確認してください。<br>

Applicants should independently verify the employer, recruiter, job conditions, and other relevant information.<br>

7. 個人間取引について<br>
Peer-to-Peer Transactions<br>

当サイトでは、ユーザー同士の商品・サービスの取引に関する投稿を認めています。<br>

We allow users to post about buying, selling, exchanging, and providing goods or services to one another.<br>

ただし、当サイトは取引の当事者ではありません。<br>

However, the Site is not a party to transactions between users.<br>

取引を行う場合<br>
When Making a Transaction<br>
相手の情報を確認してください / Verify the other party.<br>
商品・サービスの内容を確認してください / Confirm the goods or services.<br>
価格・支払方法を事前に確認してください / Confirm the price and payment method.<br>
必要に応じて安全な場所で会ってください / Meet in a safe location when appropriate.<br>
不自然な前払い要求などには注意してください / Be cautious of unusual requests for advance payment.<br>
<br>
トラブルについて<br>
About Transaction Disputes<br>

商品の未着、支払い、返金、品質、キャンセルなど、ユーザー間の取引に関するトラブルは、原則として当事者間で解決してください。<br>

Disputes involving payment, delivery, refunds, product quality, cancellations, or other transaction matters should generally be resolved between the parties involved.<br>

ただし、詐欺、脅迫、嫌がらせ、違法行為などが疑われる場合は、運営者へ通報してください。<br>

If you suspect fraud, threats, harassment, illegal activity, or other serious violations, please report the content to us.<br>

8. イベントについて<br>
Events<br>

イベントを掲載する場合は、参加者が判断できるよう、正確な情報を掲載してください。<br>

When posting an event, provide accurate information so that potential participants can make informed decisions.<br>

特に以下の情報を明確にすることをおすすめします。<br>

We recommend clearly stating:<br>

イベント名 / Event name<br>
日時 / Date and time<br>
場所 / Location<br>
料金 / Fee<br>
主催者 / Organizer<br>
参加条件 / Eligibility or requirements<br>
連絡方法 / Contact information<br>

参加者は、イベントの内容や安全性を自分自身で確認してください。<br>

Participants should independently evaluate the event, organizer, conditions, and safety before attending.<br>

9. 禁止されているコンテンツ<br>
Prohibited Content<br>

以下のコンテンツは禁止します。<br>

The following content is prohibited:<br>

🚫 違法行為 / Illegal Activities<br>

フィリピン共和国の法律その他適用される法律に違反する内容。<br>

Content involving violations of Philippine law or other applicable laws.<br>

🚫 詐欺 / Fraud<br>

他人を騙して金銭や個人情報を取得する行為。<br>

Content or activity intended to deceive people into providing money, property, or personal information.<br>

🚫 危険な行為 / Dangerous Activities<br>

他人に重大な危害を与える可能性がある行為を助長する内容。<br>

Content that encourages activities likely to cause serious harm to others.<br>

🚫 個人情報の悪用 / Misuse of Personal Information<br>

他人の個人情報を無断で公開、収集、利用する行為。<br>

Unauthorized publication, collection, or misuse of another person's personal information.<br>

🚫 なりすまし / Impersonation<br>

他人、企業、団体、運営者などになりすます行為。<br>

Pretending to be another person, business, organization, or Site operator.<br>

🚫 スパム / Spam<br>

コミュニティにとって意味のない大量投稿、迷惑広告など。<br>

Mass posting, repetitive content, or unwanted advertising that disrupts the community.<br>

10. 外部リンクについて<br>
External Links<br>

ユーザーが投稿した外部サイト、SNS、オンラインショップなどのリンクについて、運営者はその安全性、正確性、合法性を保証しません。<br>

We do not guarantee the safety, accuracy, legality, or reliability of external websites, social media accounts, online stores, or other links posted by users.<br>

リンクをクリックする際は、ユーザー自身の責任で確認してください。<br>

Users should exercise their own judgment and caution when accessing external links.<br>

11. 通報について<br>
Reporting<br>

ガイドラインに違反していると思われる投稿を見つけた場合は、当サイトの通報機能から報告してください。<br>

If you find content that may violate these guidelines, please report it using the reporting function provided by the Site.<br>

通報を行う場合は、可能な限り具体的な理由を記載してください。<br>

When making a report, please provide a clear and specific reason whenever possible.<br>

運営者は通報内容を確認し、必要に応じて以下の措置を行うことがあります。<br>

We may take appropriate action after reviewing a report, including:<br>
<br>
投稿の削除 / Content removal<br>
投稿の非公開 / Restriction or hiding of content<br>
警告 / Warning<br>
アカウントの一時停止 / Temporary account suspension<br>
アカウントの停止・削除 / Account suspension or termination<br>
その他必要な措置 / Other appropriate measures<br>
<br>
すべての通報について削除やアカウント停止を行うことを保証するものではありません。<br>
<br>
We do not guarantee that every report will result in content removal or account action.<br>
<br>
12. 運営による対応<br>
Enforcement<br>

運営者は、コミュニティの安全性と健全性を維持するため、必要に応じて投稿やアカウントに対して対応を行います。<br>

We may take action against content or accounts when reasonably necessary to maintain a safe and healthy community.<br>

対応内容は、違反の内容や重大性、繰り返しの有無などを考慮して判断します。<br>

Actions may depend on the nature and severity of the violation, whether the behavior is repeated, and other relevant circumstances.<br>

重大な違反については、事前の警告なくアカウントを停止または削除する場合があります。<br>

For serious violations, we may suspend or terminate an account without prior warning.<br>

13. 安全なコミュニティを一緒に作りましょう<br>
Let's Build a Better Community Together<br>

このコミュニティは、運営者だけでなく、参加するすべてのユーザーによって作られています。<br>

This community is built not only by its operators, but by everyone who participates.<br>

相手を尊重し、正確な情報を共有し、不審な投稿を見つけた場合は通報してください。<br>

Treat others with respect, share accurate information, and report suspicious or harmful content.<br>

Share. Connect. Help. Respect.<br>

シェアする。つながる。助け合う。尊重する。<br>
