3. Prohibited Events

違法行為を目的とするイベント、詐欺的な募集、危険性を隠したイベント、差別・嫌がらせを助長するイベント、権利侵害または重大な安全上の問題を伴うイベントは禁止します。

Events involving illegal activity, fraudulent recruitment, concealed
safety risks, promotion of discrimination or harassment, infringement of
rights, or serious safety concerns are prohibited.

4. 料金・返金・キャンセル

4. Fees, Refunds, and Cancellations

参加料金、返金条件、キャンセル期限、開催中止時の対応は、開催者が明確に表示し、適用法令を遵守してください。運営者が決済や返金を直接処理すると明示していない限り、開催者と参加者が責任を持って対応します。

Organizers must clearly disclose participation fees, refund terms,
cancellation deadlines, and arrangements if an event is cancelled, and
comply with applicable law. Unless the Operator expressly states that it
processes payments or refunds, these matters are handled by the
organizer and participant.

5. 参加者の安全と個人情報

5. Participant Safety and Personal Data

開催者は、参加者の安全に合理的な配慮をし、収集した個人情報をイベント運営に必要な範囲で適切に取り扱うものとします。参加者の連絡先や写真等を、適切な根拠なく公開・転用してはいけません。

Organizers must take reasonable steps to protect participant safety and
handle collected personal information only as appropriate for the event.
Do not publish or reuse participants' contact details or images without
an appropriate basis.

6. 中止・変更・苦情

6. Cancellations, Changes, and Complaints

開催者は、日時、場所、内容等を変更または中止する場合、参加者へ速やかに通知してください。参加者からの苦情や返金請求については、開催者が誠実に対応するものとします。

Organizers must promptly notify participants of material changes or
cancellations and respond fairly to complaints and refund requests.

