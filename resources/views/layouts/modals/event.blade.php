These Terms apply to users who announce or organize events, meetups,
classes, gatherings, and other activities through the Service.

2. 開催者の責任

2. Organizer Responsibilities

開催者は、イベントの内容、日時、場所、料金、参加条件、定員、キャンセル条件、主催者の連絡先等について、正確で最新の情報を掲載するものとします。

Organizers must provide accurate and current information about the
event's content, date, time, venue, fees, eligibility, capacity,
cancellation terms, and contact details.

開催者は、会場の許可、必要な許認可、保険、安全対策、参加者への説明その他イベント運営に必要な事項を、自ら確認・手配する責任を負います。

Organizers are responsible for confirming and arranging venue
permissions, required permits, insurance, safety measures, participant
disclosures, and other event requirements.

