                        <strong>店舗・事業者広告ポリシー</strong> <br>
                        <strong>Business Advertising Policy</strong> <br>

制定日 / Effective Date：20XX年XX月XX日<br>
<br>
1. 目的<br>
<br>
1. Purpose<br>
<br>
本ポリシーは、店舗、個人事業主、企業、サービス提供者等が本サービス上で広告や事業情報を掲載する際のルールを定めます。<br>
<br>
This Policy governs advertisements and business information posted by<br>
shops, sole proprietors, companies, and service providers.<br>
<br>
2. 掲載者の責任<br>
<br>
2. Advertiser Responsibilities<br>
<br>
掲載者は、事業者名、連絡先、所在地、商品・サービスの内容、価格、条件、営業時間等について、正確で最新の情報を掲載し、必要な許認可を自ら確認するものとします。<br>
<br>
Advertisers must provide accurate, current business names, contact<br>
details, locations, product or service descriptions, prices, terms, and<br>
operating hours, and must verify any required permits or licenses.<br>
<br>
3. 広告内容の基準<br>
<br>
3. Advertising Standards<br>
<br>
広告は、誤解を招かず、重要な条件を隠さず、適用法令を遵守するものとします。虚偽の実績、偽のレビュー、根拠のない保証、他者の商標や画像の無断使用は禁止します。<br>
<br>
Advertisements must not mislead, conceal material terms, or violate<br>
applicable law. False claims of performance, fake reviews, unsupported<br>
guarantees, and unauthorized use of another person's trademarks or<br>
images are prohibited.<br>
<br>
4. 禁止される広告<br>
<br>
4. Prohibited Advertisements<br>
<br>
違法な商品・サービス / Illegal goods or services.<br>
<br>
詐欺、フィッシング、マルウェア / Fraud, phishing, or malware.<br>
<br>
虚偽または重大な誤解を招く表示 / False or materially misleading<br>
claims.<br>
<br>
偽の推薦、レビュー、評価 / Fake endorsements, reviews, or ratings.<br>
<br>
無許可の大量投稿やスパム / Unauthorized mass posting or spam.<br>
<br>
差別、嫌がらせ、脅迫を含む広告 / Advertisements involving<br>
discrimination, harassment, or threats.<br>
<br>
他人の知的財産権やプライバシーを侵害する広告 / Ads infringing<br>
intellectual property or privacy rights.<br>
<br>
5. 価格・条件の表示<br>
<br>
5. Prices and Terms<br>
<br>
価格、追加料金、対象地域、提供条件、キャンセル・返金条件等、利用者の判断に重要な事項は明確に表示してください。広告の表示は、適用される消費者保護その他の法令に従う必要があります。<br>
<br>
Clearly disclose prices, additional charges, service areas, eligibility,<br>
cancellation and refund terms, and other material information.<br>
Advertisements must comply with applicable consumer-protection and other<br>
laws.<br>
<br>
6. 審査・広告の削除<br>
<br>
6. Review and Removal<br>
<br>
運営者は、広告を事前にすべて審査する義務を負うものではありませんが、規約違反や安全上の懸念がある場合、追加情報を求め、広告の非公開・削除、掲載制限、アカウント措置等を行う場合があります。<br>
<br>
The Operator is not required to pre-review every advertisement. However,<br>
where a violation or safety concern is suspected, we may request<br>
additional information, hide or remove an advertisement, limit posting,<br>
or take account action.<br>
<br>
7. 運営者の役割<br>
<br>
7. Role of the Operator<br>
<br>
広告掲載は、運営者による事業者、商品、サービスの推薦や保証を意味しません。購入・契約前に、利用者は事業者と条件を確認してください。<br>
<br>
Publication of an advertisement does not mean that the Operator endorses<br>
or guarantees the business, product, or service. Users should verify the<br>
business and terms before purchasing or contracting.<br>
