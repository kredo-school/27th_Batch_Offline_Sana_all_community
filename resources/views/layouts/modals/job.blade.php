                        <strong>求人掲載ポリシー</strong> <br>
                        <strong>Job Posting Policy</strong> <br>
制定日 / Effective Date：20XX年XX月XX日

1. 目的

1. Purpose

本ポリシーは、求人掲載者が正確で誠実な求人情報を掲載し、求職者が内容を判断しやすい環境を維持するためのルールです。

This Policy sets standards for accurate and honest job listings and
helps applicants assess opportunities.

2. 求人掲載者の責任

2. Responsibilities of Job Posters

求人掲載者は、雇用主または正当な採用代理人であることを確認し、職務内容、勤務地、雇用形態、給与・待遇、応募条件、勤務時間、応募方法等を正確に表示するものとします。

Job posters must be the employer or an authorized recruiter and
accurately describe duties, work location, employment type, compensation
and benefits, qualifications, working hours, and application method.

3. 禁止される求人

3. Prohibited Listings

以下の求人は禁止します。

The following listings are prohibited:

架空または詐欺的な求人 / Fake or fraudulent job opportunities.

実態と異なる給与、職務、雇用条件 / Materially misleading salary,
duties, or employment terms.

不適切または違法な応募料・採用料等の要求 / Improper or unlawful
application, recruitment, or placement fees.

違法な差別や適用法令に反する雇用条件 / Unlawful discrimination or
employment conditions.

個人情報や身分証明書等の不必要な収集 / Unnecessary collection of
personal data or identity documents.

違法な活動への勧誘、身元を偽る採用 / Recruitment for illegal
activity or under a false identity.

求人と無関係な商品購入、投資、送金等を求める内容 / Requests to
purchase unrelated products, invest, or transfer money.

違法な商品・サービスや詐欺を宣伝する内容 / Promotion of illegal
goods, services, or scams.

4. 求職者への注意

4. Applicant Precautions

応募者は、雇用主、会社の実在性、勤務地、給与、契約条件、採用担当者等を自分自身で確認してください。応募前に金銭の送金や機密情報の提供を求められた場合は、慎重に判断してください。

Applicants should independently verify the employer, company, work
location, compensation, contract terms, and recruiter. Exercise caution
if asked to transfer money or provide sensitive information before
verifying the opportunity.

5. 掲載内容の確認・削除

5. Review and Removal

運営者は、すべての求人の真正性や合法性を保証しません。違反の疑いがある求人について、追加情報を求めたり、掲載を非公開・削除したり、掲載者のアカウントを制限したりする場合があります。

The Operator does not guarantee the authenticity or legality of every
job listing. We may request further information, hide or remove a
listing, or restrict the poster's account where a violation is
suspected.

6. 運営者の役割

6. Role of the Operator

運営者は求人情報を掲載する場を提供しますが、特に明示した場合を除き、雇用主、採用代理人、応募者の代理人ではなく、雇用関係や採用結果を保証しません。

The Operator provides a platform for job listings but is not the
employer, recruitment agent, or applicant's representative and does not
guarantee employment or hiring outcomes unless expressly stated.

