                        <strong>求人掲載ポリシー</strong> <br>
                        <strong>Job Posting Policy</strong> <br>
制定日 / Effective Date：20XX年XX月XX日<br>
<br>
1. 目的<br>
<br>
1. Purpose<br>
<br>
本ポリシーは、求人掲載者が正確で誠実な求人情報を掲載し、求職者が内容を判断しやすい環境を維持するためのルールです。<br>
<br>
This Policy sets standards for accurate and honest job listings and<br>
helps applicants assess opportunities.<br>
<br>
2. 求人掲載者の責任<br>
<br>
2. Responsibilities of Job Posters<br>
<br>
求人掲載者は、雇用主または正当な採用代理人であることを確認し、職務内容、勤務地、雇用形態、給与・待遇、応募条件、勤務時間、応募方法等を正確に表示するものとします。<br>
<br>
Job posters must be the employer or an authorized recruiter and<br>
accurately describe duties, work location, employment type, compensation<br>
and benefits, qualifications, working hours, and application method.<br>
<br>
3. 禁止される求人<br>
<br>
3. Prohibited Listings<br>
<br>
以下の求人は禁止します。<br>
<br>
The following listings are prohibited:<br>
<br>
架空または詐欺的な求人 / Fake or fraudulent job opportunities.<br>
<br>
実態と異なる給与、職務、雇用条件 / Materially misleading salary,<br>
duties, or employment terms.<br>
<br>
不適切または違法な応募料・採用料等の要求 / Improper or unlawful<br>
application, recruitment, or placement fees.<br>
<br>
違法な差別や適用法令に反する雇用条件 / Unlawful discrimination or<br>
employment conditions.<br>
<br>
個人情報や身分証明書等の不必要な収集 / Unnecessary collection of<br>
personal data or identity documents.<br>
<br>
違法な活動への勧誘、身元を偽る採用 / Recruitment for illegal<br>
activity or under a false identity.<br>
<br>
求人と無関係な商品購入、投資、送金等を求める内容 / Requests to<br>
purchase unrelated products, invest, or transfer money.<br>
<br>
違法な商品・サービスや詐欺を宣伝する内容 / Promotion of illegal<br>
goods, services, or scams.<br>
<br>
4. 求職者への注意<br>
<br>
4. Applicant Precautions<br>
<br>
応募者は、雇用主、会社の実在性、勤務地、給与、契約条件、採用担当者等を自分自身で確認してください。応募前に金銭の送金や機密情報の提供を求められた場合は、慎重に判断してください。<br>
<br>
Applicants should independently verify the employer, company, work<br>
location, compensation, contract terms, and recruiter. Exercise caution<br>
if asked to transfer money or provide sensitive information before<br>
verifying the opportunity.<br>
<br>
5. 掲載内容の確認・削除<br>
<br>
5. Review and Removal<br>
<br>
運営者は、すべての求人の真正性や合法性を保証しません。違反の疑いがある求人について、追加情報を求めたり、掲載を非公開・削除したり、掲載者のアカウントを制限したりする場合があります。<br>
<br>
The Operator does not guarantee the authenticity or legality of every<br>
job listing. We may request further information, hide or remove a<br>
listing, or restrict the poster's account where a violation is<br>
suspected.<br>
<br>
6. 運営者の役割<br>
<br>
6. Role of the Operator<br>
<br>
運営者は求人情報を掲載する場を提供しますが、特に明示した場合を除き、雇用主、採用代理人、応募者の代理人ではなく、雇用関係や採用結果を保証しません。<br>
<br>
The Operator provides a platform for job listings but is not the<br>
employer, recruitment agent, or applicant's representative and does not<br>
guarantee employment or hiring outcomes unless expressly stated.<br>
