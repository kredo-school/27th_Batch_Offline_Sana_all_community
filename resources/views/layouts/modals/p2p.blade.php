                        <strong>個人間取引ポリシー</strong> <br>
                        <strong>Peer-to-Peer Transaction Policy</strong> <br>
 <br>
制定日 / Effective Date：20XX年XX月XX日<br>
<br>
1. 目的・適用範囲<br>
<br>
1. Purpose and Scope<br>
<br>
本ポリシーは、ユーザーが商品、サービス、譲渡、売買その他の個人間取引に関する情報を掲載する場合に適用されます。<br>
<br>
This Policy applies to user listings for goods, services, transfers,<br>
sales, and other peer-to-peer transactions.<br>
<br>
2. 取引当事者の責任<br>
<br>
2. Responsibility of Transaction Parties<br>
<br>
売主・買主その他の取引当事者は、相手方の確認、商品の状態、価格、支払方法、受渡し、配送、キャンセル、返金その他の条件を自ら確認し、合意するものとします。<br>
<br>
Sellers, buyers, and other parties are responsible for verifying each<br>
other and agreeing on item condition, price, payment, delivery,<br>
shipping, cancellation, refunds, and other terms.<br>
<br>
3. 禁止される取引<br>
<br>
3. Prohibited Transactions<br>
<br>
違法な商品・サービス、盗品、詐欺、偽造品、危険物、適用法令により規制・禁止される物品やサービス、虚偽の説明、他人の権利を侵害する取引は禁止します。<br>
<br>
Transactions involving illegal goods or services, stolen property,<br>
fraud, counterfeit goods, dangerous items, regulated or prohibited<br>
items, false descriptions, or infringement of others' rights are<br>
prohibited.<br>
<br>
4. 支払い・配送・返金<br>
<br>
4. Payment, Delivery, and Refunds<br>
<br>
運営者が明示的に決済サービスを提供している場合を除き、運営者は支払い、配送、商品の状態、返金、キャンセル、保証を処理または保証しません。取引前に条件を記録し、安全な支払い・受渡し方法を検討してください。<br>
<br>
Unless the Operator expressly provides a payment service, the Operator<br>
does not process or guarantee payment, delivery, item condition,<br>
refunds, cancellations, or warranties. Record the agreed terms and<br>
consider safe payment and handover methods before proceeding.<br>
<br>
5. 安全な取引<br>
<br>
5. Safer Transactions<br>
<br>
ユーザーは、相手の身元や商品情報を可能な範囲で確認し、不審な送金要求、過度に有利な条件、身分証明書等の不必要な要求に注意してください。対面取引では、安全で公共性のある場所を選ぶなど、合理的な安全対策を講じてください。<br>
<br>
Users should verify the other party and item details where possible and<br>
be cautious of suspicious payment requests, implausibly favorable<br>
offers, and unnecessary requests for identity documents. For in-person<br>
transactions, consider reasonable precautions such as choosing a safe<br>
public location.<br>
<br>
6. 個人情報<br>
<br>
6. Personal Information<br>
<br>
取引に必要な範囲を超えて個人情報を求めたり、相手の住所、電話番号、身分証明書、会話内容等を同意なく公開したりしないでください。<br>
<br>
Do not request more personal information than is reasonably necessary or<br>
publish another party's address, phone number, identity documents, or<br>
conversations without appropriate permission or lawful basis.<br>
<br>
7. 紛争と運営者の関与<br>
<br>
7. Disputes and Operator Involvement<br>
<br>
運営者は取引の当事者ではなく、商品の品質、未着、支払い、返金、キャンセル、価格、契約条件等に関する通常の紛争には原則として介入しません。ユーザーは必要に応じて当事者間で解決を図り、適切な専門家や公的機関に相談してください。<br>
<br>
The Operator is not a party to user transactions and generally does not<br>
mediate ordinary disputes about quality, non-delivery, payment, refunds,<br>
cancellations, pricing, or contract terms. Users should attempt to<br>
resolve such disputes directly and seek appropriate professional or<br>
public assistance where necessary.<br>
<br>
ただし、詐欺、違法行為、脅迫、嫌がらせ、個人情報の悪用、盗品の疑い、または本サービスの規約違反が疑われる場合、運営者は関連する投稿やアカウントに対して調査・制限等を行うことがあります。<br>
<br>
However, where fraud, illegal activity, threats, harassment, misuse of<br>
personal information, suspected stolen goods, or another policy<br>
violation is suspected, the Operator may review and restrict the<br>
relevant content or account.<br>
<br>
8. 通報<br>
<br>
8. Reporting<br>
<br>
不審な取引や規約違反を見つけた場合は、対象投稿のURL、問題の内容、関連する証拠等を可能な範囲で添えて通報してください。<br>
<br>
If you identify a suspicious transaction or policy violation, report it<br>
with the listing URL, a description of the concern, and relevant<br>
evidence where possible.<br>
<br>
9. 運営者の免責<br>
<br>
9. Operator Disclaimer<br>
<br>
運営者は、ユーザーの身元、掲載情報、商品・サービスの品質、取引の履行、支払い、配送等を保証しません。本条は、適用法令上排除できない責任を免除するものではありません。<br>
<br>
The Operator does not guarantee user identity, listing accuracy, product<br>
or service quality, transaction performance, payment, or delivery. This<br>
clause does not exclude liability that cannot legally be excluded.<br>
